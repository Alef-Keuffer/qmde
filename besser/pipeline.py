"""The whole chain, one command: problem model -> T1 -> QUBO -> T2 -> QuantumCircuit -> T3 (BESSER's
QiskitGenerator) -> run on Aer -> decode -> schedules in domain terms.

Usage (from besser/, with the venv of README.md):
    python pipeline.py              every instance in instances/
    python pipeline.py tiny none    only these

For instance <name>: instances/<name>.py (Problem DSL of Part I) and config/<name>.py (Solver Configuration DSL)
go in; output/<name>/ gets one file per step, all generated, never edited by hand:
    1_problem.py/.json, 1_config.py/.json     the input models, as loaded and validated
    2_solution.py/.json, 2_trace.json         T1: the QUBO (Solution DSL of Part I) and variable -> exam, slot
    3_quantum.py/.json, 3_trace.json          T2: the QAOA circuit (BESSER quantum metamodel) and qubit -> variable
    4_qiskit/qiskit_circuit.py, run.log       T3: the code generated by BESSER's QiskitGenerator, and its output
    5_solutions.json                          counts decoded into schedules
    6_validation.json                         the classical baseline (brute force) and the metrics
    7_problem_solved.py/.json                 bonus: the best schedule written back into the problem model
When every instance runs, output/summary.md gets one table with all of them.
"""

import contextlib
import io
import json
import sys
from pathlib import Path

from besser.generators.qiskit import QiskitGenerator

from tests import baseline
from transformations import map_back, model_io
from transformations.t1_problem2solution import transform as t1
from transformations.t2_solution2quantum import transform as t2

ROOT = Path(__file__).resolve().parent


def write_json(path: Path, data) -> None:
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def write_json_lines(path: Path, items: list) -> None:
    """A JSON list with one item per line: compact, and still readable and diffable."""
    lines = (json.dumps(item, ensure_ascii=False) for item in items)
    path.write_text("[\n" + ",\n".join(lines) + "\n]\n", encoding="utf-8")


def check(what: str, errors: list) -> None:
    if errors:
        raise SystemExit(f"{what} is not valid:\n  " + "\n  ".join(errors))


def run(name: str, out_root: Path = ROOT / "output") -> dict:
    out = Path(out_root) / name
    out.mkdir(parents=True, exist_ok=True)

    # Inputs: load and validate (structure, then OCL) before transforming anything
    problem = model_io.load_buml(ROOT / "instances" / f"{name}.py")["object_model"]
    config = model_io.load_buml(ROOT / "config" / f"{name}.py")["object_model"]
    check(f"instances/{name}.py", model_io.validate_problem(problem)
          + model_io.check_ocl(model_io.problem_metamodel(), problem))
    check(f"config/{name}.py", config.validate(raise_exception=False)["errors"]
          + model_io.check_ocl(model_io.config_metamodel(), config))
    model_io.save_models(out / "1_problem", model_io.problem_metamodel(), problem, f"Problem model of {name}")
    model_io.save_models(out / "1_config", model_io.config_metamodel(), config, f"Solver Configuration of {name}")
    settings = model_io.objects_of(config, "SolverConfig")[0]

    # T1: problem -> QUBO (Solution DSL of Part I)
    solution, trace_t1 = t1(problem, config)
    check("T1 output", solution.validate(raise_exception=False)["errors"])
    model_io.save_models(out / "2_solution", model_io.solution_metamodel(), solution, f"QUBO of {name} (T1)")
    write_json(out / "2_trace.json", trace_t1)

    # T2: QUBO -> QAOA circuit (BESSER quantum metamodel)
    circuit, trace_t2 = t2(solution, config)
    model_io.save_circuit(out / "3_quantum", circuit)
    write_json(out / "3_trace.json", trace_t2)

    # T3: BESSER's QiskitGenerator, then run the generated script unchanged on Aer
    with contextlib.redirect_stdout(io.StringIO()):
        QiskitGenerator(circuit, output_dir=str(out / "4_qiskit"), shots=settings.shots).generate()
    counts = model_io.run_generated(out / "4_qiskit" / "qiskit_circuit.py", settings.seed, out / "4_qiskit" / "run.log")

    # Backward: counts -> schedules
    qubo = model_io.read_qubo(solution)
    solutions = map_back.decode(counts, qubo, trace_t1, trace_t2)
    write_json_lines(out / "5_solutions.json", solutions)

    # Validation against the classical baseline
    reference = baseline.brute_force(problem)
    energies = baseline.spectrum(qubo)
    results = baseline.metrics(solutions, reference, energies, trace_t1["conflict_weight"])
    write_json(out / "6_validation.json", {"baseline": reference, "qubo_spectrum": energies, "metrics": results})

    # Bonus: the best measured schedule written back into a fresh copy of the problem model
    best = map_back.best_solution(solutions, reference["optimum_conflicts"])
    if best is not None:
        solved = map_back.write_back(model_io.load_buml(ROOT / "instances" / f"{name}.py")["object_model"], best)
        check("the solved problem model", solved.validate(raise_exception=False)["errors"]
              + model_io.check_ocl(model_io.problem_metamodel(), solved))  # now without W4: every exam has a slot
        model_io.save_models(out / "7_problem_solved", model_io.problem_metamodel(), solved,
                             f"Problem model of {name} with the schedule measured {best['count']} times")

    report(name, len(trace_t2["qubits"]), settings, solutions, reference, results)
    return {"name": name, "qubits": len(trace_t2["qubits"]),
            "operations": len(model_io.circuit_to_json(circuit)["operations"]),  # every gate and measurement
            "bit_strings": len(counts),  # distinct bit strings among the shots
            "baseline": reference, "metrics": results}


def report(name, qubits, settings, solutions, reference, results) -> None:
    print(f"== {name}: {qubits} qubits, QAOA p={settings.depth}, {results['shots']} shots, seed {settings.seed}")
    optimum = reference["optimum_conflicts"]
    best = map_back.best_solution(solutions, optimum)
    if best is None:
        best = min(solutions, key=lambda s: (s["energy"], -s["count"]))
        print(f"   no optimal schedule measured; lowest energy, measured {best['count']} times:")
    else:
        kind = "valid" if optimum == 0 else f"optimal ({optimum} conflict{'s' if optimum != 1 else ''})"
        print(f"   most frequent {kind} schedule, measured {best['count']} times:")
    for slot, exams in map_back.by_slot(best["schedule"]).items():
        print(f"     {slot}: {', '.join(exams)}")
    if best["broken"]:
        print(f"     broken: {', '.join(best['broken'])}")
    print(f"   baseline: {reference['valid']} valid of {reference['schedules']} schedules, fewest conflicts "
          f"{optimum} ({reference['optimal']} optimal); QUBO agrees: {results['qubo_matches_baseline']}")
    print(f"   P(valid)   {results['p_valid']:.4f}   (random {results['random_p_valid']:.2g})")
    print(f"   P(optimal) {results['p_optimal']:.4f}   (random {results['random_p_optimal']:.2g})")
    print(f"   ratio      {results['approximation_ratio']:.4f}   (random {results['random_approximation_ratio']:.4f})")


def summary(runs: list) -> str:
    """One Markdown table: every instance against its baseline and against random guessing."""
    rows = ["| Instance | Qubits | Valid schedules | Fewest conflicts | QUBO = baseline | P(valid) | P(optimal) "
            "| P(optimal), random | Ratio | Ratio, random | Operations | Bit strings |",
            "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in sorted(runs, key=lambda r: (r["qubits"], r["name"])):
        b, m = r["baseline"], r["metrics"]
        rows.append(f"| {r['name']} | {r['qubits']} | {b['valid']} of {b['schedules']} | {b['optimum_conflicts']} "
                    f"| {'yes' if m['qubo_matches_baseline'] else 'NO'} | {m['p_valid']:.4f} | {m['p_optimal']:.4f} "
                    f"| {m['random_p_optimal']:.2g} | {m['approximation_ratio']:.3f} "
                    f"| {m['random_approximation_ratio']:.3f} | {r['operations']} | {r['bit_strings']} |")
    return "\n".join(rows) + "\n"


if __name__ == "__main__":
    instances = sorted(p.stem for p in (ROOT / "instances").glob("*.py"))
    names = sys.argv[1:] or instances
    table = summary([run(instance) for instance in names])
    print("\n" + table)
    if names == instances:
        (ROOT / "output" / "summary.md").write_text(
            "# Results of `python pipeline.py`\n\nGenerated by pipeline.py: do not edit. QAOA with the fixed "
            "schedule of config/<instance>.py; random = one bit string drawn uniformly from all 2^n. Operations = "
            "every gate and measurement of the circuit; bit strings = the distinct bit strings among the shots.\n\n"
            + table,
            encoding="utf-8")
